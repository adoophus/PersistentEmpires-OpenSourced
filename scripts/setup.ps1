<#
.SYNOPSIS
  Locates (or installs) the Bannerlord client + dedicated server and writes Directory.Build.props.user.
.DESCRIPTION
  Idempotent. Exit 0 = success, 2 = setup error. Never reads or prints the dedicated-server auth token.
  Server lookup order: -ServerPath, existing Directory.Build.props.user, Steam library folders, steamcmd install.
#>
[CmdletBinding()]
param(
    [string]$ClientPath,
    [string]$ServerPath,
    [string]$SteamCmdPath,
    [switch]$SkipServerInstall
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$userProps = Join-Path $repo 'Directory.Build.props.user'
$clientDirName = 'Mount & Blade II Bannerlord'
$serverDirName = 'Mount & Blade II Dedicated Server'
$serverAppId = 1863440

function Fail([string]$m) { Write-Host "ERROR: $m" -ForegroundColor Red; exit 2 }
function Test-Client([string]$p) { $p -and (Test-Path -LiteralPath (Join-Path $p 'bin\Win64_Shipping_Client\TaleWorlds.Core.dll')) }
function Test-Server([string]$p) { $p -and (Test-Path -LiteralPath (Join-Path $p 'bin\Win64_Shipping_Server\TaleWorlds.Core.dll')) }

function Get-SteamLibraries {
    $steam = $null
    try { $steam = (Get-ItemProperty 'HKCU:\Software\Valve\Steam' -ErrorAction Stop).SteamPath } catch { }
    if (-not $steam) { $steam = Join-Path ${env:ProgramFiles(x86)} 'Steam' }
    $steam = $steam -replace '/', '\'
    $libs = @($steam)
    $vdf = Join-Path $steam 'steamapps\libraryfolders.vdf'
    if (Test-Path -LiteralPath $vdf) {
        foreach ($m in [regex]::Matches((Get-Content -LiteralPath $vdf -Raw), '"path"\s+"([^"]+)"')) {
            $libs += ($m.Groups[1].Value -replace '\\\\', '\')
        }
    }
    $libs | Select-Object -Unique
}

function Get-ExistingUserValue([string]$name) {
    if (Test-Path -LiteralPath $userProps) {
        $m = [regex]::Match((Get-Content -LiteralPath $userProps -Raw), "<$name>([^<]*)</$name>")
        if ($m.Success) { return [System.Net.WebUtility]::HtmlDecode($m.Groups[1].Value) }
    }
}

# --- client ---
if (-not $ClientPath) {
    foreach ($lib in Get-SteamLibraries) {
        $c = Join-Path $lib "steamapps\common\$clientDirName"
        if (Test-Client $c) { $ClientPath = $c; break }
    }
}
if (-not $ClientPath) { $ClientPath = Get-ExistingUserValue 'BannerlordClientPath' }
if (-not (Test-Client $ClientPath)) { Fail "Bannerlord client not found. Install it via Steam or pass -ClientPath <dir containing bin\Win64_Shipping_Client>." }
Write-Host "Client : $ClientPath"

# --- server ---
if (-not $ServerPath) { $ServerPath = Get-ExistingUserValue 'BannerlordServerPath' }
if (-not (Test-Server $ServerPath)) {
    foreach ($lib in Get-SteamLibraries) {
        $c = Join-Path $lib "steamapps\common\$serverDirName"
        if (Test-Server $c) { $ServerPath = $c; break }
    }
}
if (-not (Test-Server $ServerPath)) {
    if ($SkipServerInstall) { Fail "Dedicated server not found and -SkipServerInstall was given. Pass -ServerPath <dir>." }
    if (-not $ServerPath) { $ServerPath = Join-Path (Split-Path -Parent $repo) 'bannerlord-server' }
    if (-not $SteamCmdPath) {
        $cmd = Get-Command steamcmd -ErrorAction SilentlyContinue
        if ($cmd) { $SteamCmdPath = $cmd.Source }
    }
    if (-not $SteamCmdPath -or -not (Test-Path -LiteralPath $SteamCmdPath)) {
        Fail "steamcmd not found. Download it from https://developer.valvesoftware.com/wiki/SteamCMD and pass -SteamCmdPath <steamcmd.exe>."
    }
    Write-Host "Installing dedicated server (app $serverAppId) to $ServerPath via steamcmd ..."
    & $SteamCmdPath +force_install_dir $ServerPath +login anonymous +app_update $serverAppId validate +quit
    if (-not (Test-Server $ServerPath)) { Fail "steamcmd finished but $ServerPath\bin\Win64_Shipping_Server\TaleWorlds.Core.dll is missing (exit $LASTEXITCODE)." }
}
Write-Host "Server : $ServerPath"

# --- write props (only if changed) ---
$c1 = [System.Security.SecurityElement]::Escape($ClientPath)
$s1 = [System.Security.SecurityElement]::Escape($ServerPath)
$xml = @"
<Project>
  <!-- Generated by scripts\setup.ps1. Git-ignored; do not commit. -->
  <PropertyGroup>
    <BannerlordClientPath>$c1</BannerlordClientPath>
    <BannerlordServerPath>$s1</BannerlordServerPath>
  </PropertyGroup>
</Project>
"@
$old = if (Test-Path -LiteralPath $userProps) { Get-Content -LiteralPath $userProps -Raw } else { '' }
if ($old.Trim() -ne $xml.Trim()) {
    [IO.File]::WriteAllText($userProps, $xml + "`r`n", (New-Object Text.UTF8Encoding($false)))
    Write-Host "Wrote  : $userProps"
} else { Write-Host "Unchanged: $userProps" }

# --- auth token (existence only; contents are never read) ---
$token = Join-Path ([Environment]::GetFolderPath('MyDocuments')) 'Mount and Blade II Bannerlord\Tokens\DedicatedCustomServerAuthToken.txt'
if (Test-Path -LiteralPath $token) { Write-Host "Auth token: present" }
else {
    Write-Host "Auth token: MISSING (needed only to run the server, not to build)" -ForegroundColor Yellow
    Write-Host "  Generate it with the Bannerlord client (log in to multiplayer, then use the console command"
    Write-Host "  'customserver.gen_token'). It must end up at:"
    Write-Host "    $token"
    Write-Host "  Never commit or share that file."
}

# --- dotnet SDK ---
if (-not (Get-Command dotnet -ErrorAction SilentlyContinue)) { Fail "dotnet SDK not found. Install the .NET SDK from https://dotnet.microsoft.com/download." }
if (-not (& dotnet --list-sdks)) { Fail "dotnet is installed but no SDK was found (runtime only). Install the .NET SDK." }
Write-Host "dotnet : $(& dotnet --version)"
Write-Host "Setup OK" -ForegroundColor Green
exit 0
